"""Generate the standalone Molab base-encoder control from the shared pilot worker."""

import base64
import hashlib
import io
import zipfile
from pathlib import Path

from notebook_bundle import source_bundle_bytes
from prepare_colab_pilot import _worker_source

ROOT = Path(__file__).resolve().parents[1]


def render():
    worker = _worker_source().replace(
        "from dataclasses import replace", "from dataclasses import asdict, replace"
    )
    begin = worker.index("        step_val = details.get")
    end = worker.index("    report_path =", begin)
    worker = (
        worker[:begin]
        + "        if event_callback is not None:\n            event_callback(payload)\n\n"
        + worker[end:]
    )
    begin = worker.index("    secret = Path(")
    end = worker.index("    token = get_token()", begin)
    worker = worker[:begin] + worker[end:]
    worker = worker.replace("/content/bifocalgemma-test", "outputs/pilot/e2b-base").replace(
        "Colab CUDA", "Molab CUDA"
    )
    buffer = io.BytesIO(source_bundle_bytes(ROOT))
    with zipfile.ZipFile(buffer, "a", zipfile.ZIP_DEFLATED) as archive:
        for name, content in (
            ("tools/prepare_colab_pilot.py", worker),
            ("tools/molab_pilot_support.py", (ROOT / "tools/molab_pilot_support.py").read_text()),
        ):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, content.replace("\r\n", "\n"))
    payload = buffer.getvalue()
    checksum = hashlib.sha256(payload).hexdigest()
    encoded = base64.b85encode(payload).decode()
    literal = "        " + repr(encoded)
    dependencies = (
        (ROOT / "notebooks/legacy/v2/train_e2b_e2b.py")
        .read_text(encoding="utf-8")
        .split("# Generated by")[0]
    )
